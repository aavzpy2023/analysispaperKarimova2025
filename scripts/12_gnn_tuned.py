import concurrent.futures
import multiprocessing
import os
import sys
import time
import warnings

import numpy as np
import pandas as pd

sys.path.append(os.path.dirname(os.path.abspath(__file__)))
from paths_config import *
from logger_utils import setup_logger, explain
from splits import outer_splits
from nb_stats import compare_to_classical, nb_paired, EQUIVALENCE_MARGIN_R2, EQUIVALENCE_MARGIN_MAE
from gnn_utils import GRID, DEFAULT_CONFIG, run_outer_fold, config_name

warnings.filterwarnings("ignore")
# The workstation CPU has AVX but not AVX2; some oneDNN/MKL kernels selected at run time can raise SIGILL in a worker.
for _var, _val in (("ONEDNN_MAX_CPU_ISA", "AVX"), ("DNNL_MAX_CPU_ISA", "AVX"), ("MKL_ENABLE_INSTRUCTIONS", "AVX")):
    os.environ.setdefault(_var, _val)
# Training is already multi-threaded, so more workers do not add throughput; they only isolate a crashing worker.
N_WORKERS = max(1, int(os.environ.get("MLGNN_GNN_WORKERS", "2")))
MAX_POOL_RESTARTS = 50
INNER_CACHE_DIR = os.path.join(RESULTS_DIR, "12_inner_cache")


def load_done():
    return pd.read_csv(GNN_TUNED_CHECKPOINT) if os.path.exists(GNN_TUNED_CHECKPOINT) else pd.DataFrame()


def export_latex(scores, comparison_macros, untuned_macros):
    values = {"GnnTunedRTwoMean": f"{scores['R2'].mean():.4f}", "GnnTunedRTwoStd": f"{scores['R2'].std(ddof=1):.4f}",
              "GnnTunedMae": f"{scores['MAE'].mean():.4f}", "GnnTunedNConfigs": len(GRID),
              "GnnTunedNChosen": scores['Best_Config'].nunique(),
              "GnnTunedDefaultChosenPct": f"{(scores['Best_Config'] == config_name(DEFAULT_CONFIG)).mean() * 100:.0f}",
              "GnnTunedFoldSecMean": f"{scores['Time_s'].mean():.0f}",
              "GnnTunedTotalHours": f"{scores['Time_s'].sum() / 3600:.1f}"}
    values.update(comparison_macros)
    values.update(untuned_macros)
    os.makedirs(os.path.dirname(LATEX_GNN_TUNED), exist_ok=True)
    with open(LATEX_GNN_TUNED, "w", encoding="utf-8") as f:
        f.write("% Auto-generated by 12_gnn_tuned.py\n")
        for name, value in values.items():
            f.write(f"\\newcommand{{\\{name}}}{{{value}}}\n")
    print(f"[EXPORT] LaTeX variables saved to {LATEX_GNN_TUNED}", flush=True)


def main():
    setup_logger(os.path.join(LOGS_DIR, "12_gnn_tuned.log"))
    print("=" * 105)
    print("12_gnn_tuned.py — D-MPNN with hyperparameter search inside every outer fold (nested)")
    print("=" * 105)
    explain("What this step does", f"""
        Step 09 evaluated the D-MPNN with default settings, which a reviewer can fairly call under-tuned. Here the network gets
        the same treatment as the classical models: inside each outer training set, {len(GRID)} configurations (hidden size,
        message-passing depth and dropout) are compared on a held-out 20% of that training set, the best one is retrained on the
        whole training set, and only then it predicts the outer test fold. The outer folds are the same as in steps 01 and 09, so
        the results can be compared fold by fold. The default configuration is part of the grid.
    """)

    df = pd.read_csv(TRAIN_FILE).dropna(subset=['Smiles', 'pIC50 Value']).reset_index(drop=True)
    smiles, y = df['Smiles'].to_numpy(), df['pIC50 Value'].to_numpy()
    folds = list(outer_splits(smiles.tolist(), CFG['OUTER_N_SPLITS'], CFG['OUTER_N_REPEATS'], RANDOM_STATE, SPLIT_KIND))
    done = load_done()
    done_folds = set(done['Fold']) if not done.empty else set()
    threads = max(1, N_JOBS // N_WORKERS)
    print(f"[INFO] {len(folds)} outer folds, {len(done_folds)} already in the checkpoint; {N_WORKERS} workers x {threads} threads", flush=True)

    all_tasks = {i: (i, smiles[tr].tolist(), y[tr].tolist(), smiles[te].tolist(), y[te].tolist(), RANDOM_STATE + i, threads, INNER_CACHE_DIR)
                 for i, (tr, te) in enumerate(folds)}
    t0 = time.time()
    for attempt in range(1, MAX_POOL_RESTARTS + 2):
        pending = [t for i, t in all_tasks.items() if i not in done_folds]
        if not pending:
            break
        try:
            with concurrent.futures.ProcessPoolExecutor(max_workers=N_WORKERS, mp_context=multiprocessing.get_context("spawn")) as pool:
                futures = [pool.submit(run_outer_fold, t) for t in pending]
                for fut in concurrent.futures.as_completed(futures):
                    r = fut.result()
                    r.pop("pred")
                    pd.DataFrame([r]).to_csv(GNN_TUNED_CHECKPOINT, mode="a", header=not os.path.exists(GNN_TUNED_CHECKPOINT), index=False)
                    done_folds.add(r["Fold"])
                    print(f"  --> Fold {r['Fold'] + 1}/{len(folds)} OK | best={r['Best_Config']} | R2={r['R2']:.4f} | "
                          f"MAE={r['MAE']:.4f} | {r['Time_s']:.0f}s (elapsed {(time.time() - t0) / 60:.0f} min)", flush=True)
        except concurrent.futures.process.BrokenProcessPool:
            print(f"[WARNING] A worker process died (attempt {attempt}); restarting the pool with the folds still pending.", flush=True)

    scores = load_done().sort_values("Fold").reset_index(drop=True)
    if len(scores) != len(folds):
        print(f"[WARNING] Only {len(scores)}/{len(folds)} folds available; comparisons skipped.", flush=True)
        return
    print(f"\n[RESULT] Tuned D-MPNN: R2 = {scores['R2'].mean():.4f} +/- {scores['R2'].std(ddof=1):.4f} | MAE = {scores['MAE'].mean():.4f}", flush=True)
    print(scores['Best_Config'].value_counts().to_string(), flush=True)

    if not os.path.exists(CHECKPOINT_FILE):
        print(f"[WARNING] {CHECKPOINT_FILE} not found; run step 01 first. Comparisons skipped.", flush=True)
        return
    table, macros = compare_to_classical(scores, pd.read_csv(CHECKPOINT_FILE), "GnnTunedVs")
    table.to_csv(GNN_TUNED_VS_CLASSICAL_CSV, index=False)
    print(table.round(4).to_string(index=False), flush=True)

    untuned_macros = {}
    if os.path.exists(GNN_FOLD_SCORES_CSV):
        untuned = pd.read_csv(GNN_FOLD_SCORES_CSV).sort_values("Fold").reset_index(drop=True)
        if len(untuned) == len(scores) and (untuned['N_test'].values == scores['N_test'].values).all():
            for metric, col, margin in (("RTwo", "R2", EQUIVALENCE_MARGIN_R2), ("Mae", "MAE", EQUIVALENCE_MARGIN_MAE)):
                res = nb_paired(scores[col].values - untuned[col].values, scores['N_train'].mean(), scores['N_test'].mean(), margin)
                untuned_macros[f"GnnTunedVsUntunedDiff{metric}"] = f"{res['mean_diff']:+.4f}"
                untuned_macros[f"GnnTunedVsUntunedP{metric}"] = f"{res['p']:.3f}"
    export_latex(scores, macros, untuned_macros)
    print("[DONE] 12_gnn_tuned.py complete.")


if __name__ == "__main__":
    main()
