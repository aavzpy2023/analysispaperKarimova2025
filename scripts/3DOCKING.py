def newcommand(f, name, value):
    f.write(f"\\newcommand{{\\{name}}}{{{value}}}\n")

def export_latex(df_results):
    with open(LATEX_FILE, 'w', encoding='utf-8') as f:
        f.write("% Auto-generated by 3DOCKING.py\n")
        f.write("% Include with: \\input{docking_variables.tex}\n\n")

        n_total    = len(df_results)
        n_validated = len(df_results[
            (df_results['ML_pIC50'] > ML_ACTIVE_THRESH) &
            (df_results['Docking_Score'] < DOCK_ACTIVE_THRESH)
        ])
        n_discordant = len(df_results[
            (df_results['ML_pIC50'] > ML_ACTIVE_THRESH) &
            (df_results['Docking_Score'] >= DOCK_ACTIVE_THRESH)
        ])

        newcommand(f, "DockNTotal",      str(n_total))
        newcommand(f, "DockNValidated",  str(n_validated))
        newcommand(f, "DockNDiscordant", str(n_discordant))
        newcommand(f, "DockExhaustiveness", str(EXHAUSTIVENESS))
        newcommand(f, "DockBoxSize",     str(BOX_SIZE))
        newcommand(f, "DockCenterX",     f"{CENTER_X:.3f}")
        newcommand(f, "DockCenterY",     f"{CENTER_Y:.3f}")
        newcommand(f, "DockCenterZ",     f"{CENTER_Z:.3f}")

        # Pearson correlation ML pIC50 vs Docking score
        if len(df_results) >= 3:
            r, p = stats.pearsonr(df_results['ML_pIC50'], df_results['Docking_Score'])
            newcommand(f, "DockPearsonR", f"{r:.3f}")
            newcommand(f, "DockPearsonP", f"{p:.4f}")

        # Best candidate
        best = df_results.sort_values('Docking_Score').iloc[0]
        name_safe = "".join(c for c in str(best['Name']) if c.isalpha())[:20]
        newcommand(f, "DockBestCandidate",    name_safe)
        newcommand(f, "DockBestMLpIC",        f"{best['ML_pIC50']:.4f}") # Fixed macro name to match LaTeX
        newcommand(f, "DockBestDockScore",    f"{best['Docking_Score']:.2f}")

        # Dynamic extraction for true negative example (Chlorambucil)
        chlorambucil = df_results[df_results['Name'].str.contains('Chlorambucil', case=False, na=False)]
        if not chlorambucil.empty:
            c_row = chlorambucil.iloc[0]
            newcommand(f, "ChlorambucilMLpIC", f"{c_row['ML_pIC50']:.2f}")
            newcommand(f, "ChlorambucilDockScore", f"{c_row['Docking_Score']:.2f}")

    print(f"[LATEX] Docking variables exported to {LATEX_FILE}")

