# =========================================================
# CONFIG
# =========================================================
RECEPTOR_FILE  = RECEPTOR_PDBQT
INPUT_CSV      = FDA_CANDIDATES_CSV   # from 2FDA.py
OUTPUT_CSV     = DOCKING_RESULTS_CSV
LATEX_FILE     = LATEX_DOCKING

# Active site coordinates (detected by prep_receptor.py from crystal ligand CP6)
CENTER_X, CENTER_Y, CENTER_Z = 3.689, 39.992, -62.818
BOX_SIZE       = 20.0   # Angstroms
EXHAUSTIVENESS = 32     # Higher = more thorough (8 is standard, 32 is publication quality)
N_POSES        = 3      # Save top 3 poses per ligand

# Thresholds for ML+physics agreement interpretation
ML_ACTIVE_THRESH   = 6.5   # pIC50 > this = predicted active
DOCK_ACTIVE_THRESH = -8.0  # kcal/mol < this = docking confirms binding


# =========================================================
# LIGAND PREPARATION
# =========================================================
def prepare_ligand_pdbqt(smiles, name):
    """SMILES -> 3D conformer (ETKDGv3 + MMFF94) -> PDBQT string via Meeko."""
    try:
        from meeko import MoleculePreparation
        mol = Chem.MolFromSmiles(smiles)
        if mol is None:
            return None
        mol = Chem.AddHs(mol)
        params = AllChem.ETKDGv3()
        params.randomSeed = 42
        if AllChem.EmbedMolecule(mol, params) == -1:
            AllChem.EmbedMolecule(mol, useRandomCoords=True)
        try:
            AllChem.MMFFOptimizeMolecule(mol)
        except Exception:
            pass
        prep = MoleculePreparation()
        prep.prepare(mol)
        return prep.write_pdbqt_string()
    except Exception:
        return None


