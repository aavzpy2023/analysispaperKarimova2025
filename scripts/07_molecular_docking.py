def get_physicochemical_props(smiles):
    """Calcula MW, LogP, Rotatable Bonds y Heavy Atoms usando RDKit."""
    mol = Chem.MolFromSmiles(smiles)
    if mol is None:
        return None, None, None, None, None

    frags = Chem.GetMolFrags(mol, asMols=True)
    mol_clean = max(frags, key=lambda f: f.GetNumAtoms())

    mw = Descriptors.MolWt(mol_clean)
    logp = Descriptors.MolLogP(mol_clean)
    rot_bonds = Lipinski.NumRotatableBonds(mol_clean)
    heavy_atoms = mol_clean.GetNumHeavyAtoms()

    return mol_clean, mw, logp, rot_bonds, heavy_atoms

def prepare_ligand_pdbqt(mol_clean):
    """Genera conformación 3D y convierte a PDBQT vía Meeko."""
    try:
        from meeko import MoleculePreparation, PDBQTWriterLegacy

        mol_h = Chem.AddHs(mol_clean)
        params = AllChem.ETKDGv3()
        params.randomSeed = RANDOM_STATE
        if AllChem.EmbedMolecule(mol_h, params) == -1:
            AllChem.EmbedMolecule(mol_h, useRandomCoords=True)
        try:
            AllChem.MMFFOptimizeMolecule(mol_h)
        except Exception:
            pass

        prep = MoleculePreparation()
        mol_setups = prep.prepare(mol_h)
        pdbqt_string, is_ok, _ = PDBQTWriterLegacy.write_string(mol_setups[0])
        return pdbqt_string if is_ok else None
    except Exception as e:
        print(f"    [ligand prep] {type(e).__name__}: {str(e)[:80]}")
        return None


