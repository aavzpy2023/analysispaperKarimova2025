def newcommand(f_handle, name, value):
    f_handle.write(f"\\newcommand{{\\{name}}}{{{value}}}\n")

def export_latex(df_results):
    abs_path = os.path.abspath(LATEX_DOCKING)
    print(f"\n[LATEX] Attempting to write file to: {abs_path}")

    try:
        os.makedirs(os.path.dirname(abs_path), exist_ok=True)

        with open(abs_path, 'w', encoding='utf-8') as f:
            f.write("% Auto-generated by 07_molecular_docking.py\n")
            f.write("% Include with: \\input{docking_variables.tex}\n\n")

            n_total     = len(df_results)
            n_validated = len(df_results[df_results['Agreement'] == 'VALIDATED (+)'])
            n_discordant = len(df_results[df_results['Agreement'] == 'ML FALSE POSITIVE'])

            newcommand(f, "DockNTotal",      str(n_total))
            newcommand(f, "DockNValidated",  str(n_validated))
            newcommand(f, "DockNDiscordant", str(n_discordant))
            newcommand(f, "DockExhaustiveness", str(EXHAUSTIVENESS))
            newcommand(f, "DockBoxSize",     str(BOX_SIZE))
            newcommand(f, "DockCenterX",     f"{CENTER_X:.3f}")
            newcommand(f, "DockCenterY",     f"{CENTER_Y:.3f}")
            newcommand(f, "DockCenterZ",     f"{CENTER_Z:.3f}")

            if len(df_results) >= 3:
                rho, p = stats.spearmanr(df_results['ML_pIC50'], df_results['Docking_Score'])
                newcommand(f, "DockSpearmanRho", f"{rho:.3f}")
                newcommand(f, "DockSpearmanP", f"{p:.4f}")

            best = df_results.sort_values('Docking_Score').iloc[0]
            name_safe = "".join(c for c in str(best['Name']) if c.isalpha())[:20]
            newcommand(f, "DockBestCandidate",    name_safe)
            newcommand(f, "DockBestMLpIC",        f"{best['ML_pIC50']:.4f}")
            newcommand(f, "DockBestDockScore",    f"{best['Docking_Score']:.2f}")

            def extract_compound_metrics(file_handle, df, name_substring, prefix):
                match = df[df['Name'].str.contains(name_substring, case=False, na=False)]
                if not match.empty:
                    row = match.iloc[0]
                    newcommand(file_handle, f"{prefix}MLpIC", f"{row['ML_pIC50']:.4f}")
                    newcommand(file_handle, f"{prefix}DockScore", f"{row['Docking_Score']:.2f}")

            for search_sub, prefix in LATEX_REF_COMPOUNDS:
                extract_compound_metrics(f, df_results, search_sub, prefix)

        print(f"[LATEX] SUCCESS! Variables exported to {abs_path}")

    except Exception as e:
        print(f"[LATEX ERROR] Failed to write .tex file: {e}")


